import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ModelExporter, Parser } from '@dbml/core';

const defaultSourcePath = fileURLToPath(new URL('../database/Daily_cart.dbml', import.meta.url));

export async function generateDbmlSql(sourcePath) {
    const resolvedSourcePath = path.resolve(sourcePath);

    if (path.extname(resolvedSourcePath).toLowerCase() !== '.dbml') {
        throw new Error(`Expected a .dbml file, received: ${resolvedSourcePath}`);
    }

    const outputPath = resolvedSourcePath.replace(/\.dbml$/i, '.mysql.sql');
    const dbml = await readFile(resolvedSourcePath, 'utf8');
    const model = Parser.parse(dbml, 'dbml');
    const sql = ModelExporter.export(model, 'mysql').replaceAll(
        "COMMENT 'MySQL: ON UPDATE CURRENT_TIMESTAMP'",
        'ON UPDATE CURRENT_TIMESTAMP',
    );

    await writeFile(
        outputPath,
        `-- Generated from ${path.basename(resolvedSourcePath)}. Do not edit this file directly.\n\n${sql.trimEnd()}\n`,
        'utf8',
    );

    return outputPath;
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : '';

if (invokedPath === fileURLToPath(import.meta.url)) {
    const sourcePath = process.argv[2]
        ? path.resolve(process.argv[2])
        : defaultSourcePath;

    console.log(`Generated ${path.relative(process.cwd(), await generateDbmlSql(sourcePath))}`);
}
